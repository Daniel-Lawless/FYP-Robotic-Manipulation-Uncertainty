from __future__ import annotations

import csv
from collections.abc import Iterable
from pathlib import Path

# Comparison ignores columns that measure wall-clock time, which varies between runs and
# machines; every other value must match exactly.
TIMING_COLUMNS = ("wall_s",)


# Writing never replaces an existing file unless asked to, so a rerun cannot silently
# change a version-controlled dataset.
def write_rows(path: Path | str, rows: list[dict], overwrite: bool = False) -> None:
    path = Path(path)
    if path.exists() and not overwrite:
        raise FileExistsError(f"{path} exists; pass --overwrite to replace it")
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def read_rows(path: Path | str) -> list[dict]:
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def diff_rows(
    expected: list[dict],
    actual: list[dict],
    ignore: Iterable[str] = TIMING_COLUMNS,
    allow_extra_columns: bool = False,
) -> list[str]:
    """Human-readable differences between two datasets, ignoring the given columns.

    With allow_extra_columns, actual may have columns that expected lacks (a dataset
    regenerated by a script that has since gained columns); every column of expected is
    still compared exactly.
    """
    ignore = set(ignore)
    if expected and actual:
        columns, actual_columns = list(expected[0]), list(actual[0])
        missing = [c for c in columns if c not in actual_columns]
        if allow_extra_columns and missing:
            return [f"columns missing: {missing}"]
        if not allow_extra_columns and columns != actual_columns:
            return [f"columns differ: {columns} vs {actual_columns}"]
    diffs = []
    if len(expected) != len(actual):
        diffs.append(f"row count differs: {len(expected)} vs {len(actual)}")
    for i, (a, b) in enumerate(zip(expected, actual, strict=False)):  # lengths checked above
        diffs += [f"row {i}, {k}: {a[k]} vs {b[k]}" for k in a if k not in ignore and a[k] != b[k]]
    return diffs
